def test_unknown_age_gives_both(graph):
    g = KinGraph({1: PInfo(1, "甲", "male"), 2: PInfo(2, "乙", "male"), 3: PInfo(3, "父", "male")})
    g.add_parent(3, 1)
    g.add_parent(3, 2)
    assert g.kinship(1, 2, DEFAULT_RULES)["term"] == "哥哥/弟弟"


def test_path_explained(graph):
    r = graph.kinship(graph.ids["我"], graph.ids["小明"], DEFAULT_RULES)
    assert [s["name"] for s in r["paths"][0]["steps"]] == ["我", "母亲", "姨妈", "小明"]
    assert r["paths"][0]["description"] == "母亲的姐姐的儿子"


def test_no_relation():
    g = KinGraph({1: PInfo(1, "甲", "male"), 2: PInfo(2, "乙", "female")})
    r = g.kinship(1, 2, DEFAULT_RULES)
    assert not r["found"] and r["term"] is None


def test_multiple_paths():
    # 两位表亲结婚：B 既是 A 的妻子，又是 A 的表妹
    ppl = {i: PInfo(i, n, g, b) for i, (n, g, b) in enumerate(
        [("外公", "male", "1930"), ("母", "female", "1955"), ("姨", "female", "1958"),
         ("A", "male", "1980"), ("B", "female", "1982")], start=1)}
    g = KinGraph(ppl)
    g.add_parent(1, 2); g.add_parent(1, 3); g.add_parent(2, 4); g.add_parent(3, 5)
    g.add_spouse(4, 5)
    r = g.kinship(4, 5, DEFAULT_RULES)
    assert r["term"] == "妻子"
    assert any(p["term"] == "表妹" for p in r["paths"][1:])


def test_generations(graph):
    gens = graph.generations()
    ids = graph.ids
    assert gens[ids["曾祖父"]] == 0
    assert gens[ids["我"]] == 3
    assert gens[ids["妻子"]] == gens[ids["岳父"]] + 1
    assert gens[ids["姐夫"]] == 3  # 无父母记录，与配偶同辈
    assert gens[ids["孙子"]] == 5
